import assert from 'node:assert/strict';
import {normalizeLog,mergeMatches,stats,groupStats,makeDemo,rankedOnly} from '../lib/analysis.ts';
const tag='#TEST123';
const entry=(overrides={})=>({battleTime:'20261026T030000.000Z',event:{id:1,map:'Shooting Star',mode:'bounty'},battle:{mode:'bounty',type:'soloRanked',result:'victory',teams:[[{tag,brawler:{id:16000015,name:'PIPER',power:11}}]],...overrides}});
const r=normalizeLog([entry()],tag);
assert.equal(r.length,1);assert.equal(r[0].queue,'Ranked');assert.equal(r[0].time,'2026-10-26T03:00:00.000Z');assert.equal(r[0].trophies,null);
assert.equal(normalizeLog([entry({type:'ranked'})],tag).length,0);
assert.equal(normalizeLog([entry({type:'newUnknown'})],tag).length,0);
assert.equal(normalizeLog([entry()], '#P0LYQ').length,0);
assert.equal(mergeMatches(r,r).length,1);
const sample=[r[0],{...r[0],id:'2',result:'defeat'},{...r[0],id:'3',result:'draw'},{...r[0],id:'4',result:'placement',rank:2}];
const s=stats(sample);assert.equal(s.rate,50);assert.equal(s.n,2);assert.equal(s.draws,1);assert.equal(s.hasTrophies,false);assert.ok(s.low<50&&s.high>50);
assert.equal(stats([]).rate,null);assert.equal(stats([]).score,50);
assert.equal(normalizeLog([entry({mode:'duels'})],tag)[0].brawlerId,0);
assert.equal(normalizeLog([entry({result:undefined,rank:1})],tag)[0].result,'placement');
assert.equal(normalizeLog([null,{}, {...entry(),battleTime:'bad'}],tag).length,0);
assert.equal(groupStats(sample,m=>m.brawler)[0].n,2);
assert.equal(makeDemo().length,126);
console.log('PASS: parsing, queue separation, tag matching, deduplication, draws, placements, confidence intervals, Duels attribution and sample generation.');
const lineup=normalizeLog([entry()],tag)[0];
assert.deepEqual(lineup.allies,[{id:16000015,name:'PIPER',power:11}]);
assert.deepEqual(lineup.enemies,[]);
assert.equal(lineup.rawType,'soloRanked');

assert.equal(normalizeLog([entry({type:'friendly'})],tag).length,0);
assert.equal(normalizeLog([entry({type:'teamRanked'})],tag)[0].queue,'Ranked');
assert.equal(rankedOnly([{...r[0],queue:'Ladder'},{...r[0],rawType:'ranked'},r[0]]).length,1);
assert.equal(mergeMatches([{...r[0],id:'ladder',queue:'Ladder'}],r).length,1);
const history=Array.from({length:100},(_,i)=>({...r[0],id:'old-'+i,time:'2020-01-01T00:00:00.000Z'}));
assert.equal(mergeMatches(history,r).length,101);
console.log('PASS: Ranked-only ingestion, legacy-data exclusion, teamRanked support, and accumulation beyond 25 records without age expiry.');
